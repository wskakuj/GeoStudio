import test from "node:test";
import assert from "node:assert/strict";
import {webcrypto} from "node:crypto";
import {issuePermit} from "./offline-license.mjs";
globalThis.crypto ||= webcrypto;
const now = 1770000000;
const project = "test-geostudio";
const device = "a".repeat(64);
const key = await crypto.subtle.generateKey({name:"ECDSA",namedCurve:"P-256"},true,["sign","verify"]);
const env = {PROJECT_ID:project, SIGNING_KEY_JWK:JSON.stringify(await crypto.subtle.exportKey("jwk",key.privateKey))};
const b64 = obj=>Buffer.from(JSON.stringify(obj)).toString("base64url");
const token = "header."+b64({sub:"tester",aud:project,iss:"https://securetoken.google.com/"+project,
  exp:now+3600,email:"tester@example.invalid"})+".signature";
function req(id=device) {
  return new Request("https://example.invalid/lease",{method:"POST",
    headers:{Authorization:"Bearer "+token},body:JSON.stringify({deviceId:id})});
}
const fields = {active:{booleanValue:true},expiresAt:{nullValue:null},
  offlineHours:{integerValue:"72"},deviceLimit:{integerValue:"2"},
  devices:{arrayValue:{values:[{stringValue:device}]}}};
test("worker signs only an authorized registered device and bounds expiry", async()=>{
  const expiry=now+3600;
  const response=await issuePermit(req(),env,async(url,options)=>{
    assert.match(url,/geostudio_access\/tester$/);
    assert.equal(options.headers.Authorization,"Bearer "+token);
    assert.equal(options.redirect,"manual");
    return Response.json({fields:{...fields,expiresAt:{timestampValue:new Date(expiry*1000).toISOString()}}});
  },now);
  assert.equal(response.status,200);
  const [payload,signature]=(await response.json()).lease.split(".");
  const raw=Buffer.from(payload,"base64url"), sig=Buffer.from(signature,"base64url");
  assert.equal(sig.length,64);
  assert.equal(await crypto.subtle.verify({name:"ECDSA",hash:"SHA-256"},key.publicKey,sig,raw),true);
  assert.deepEqual(JSON.parse(raw),{v:1,project,uid:"tester",device,email:"tester@example.invalid",
    iat:now,exp:expiry,accountExp:expiry,deviceLimit:2,deviceCount:1});
});
test("worker refuses unavailable or denied Firebase and no offline policy", async()=>{
  assert.equal((await issuePermit(req(),env,async()=>new Response(null,{status:403}),now)).status,403);
  assert.equal((await issuePermit(req(),env,async()=>new Response(null,{status:500}),now)).status,503);
  assert.equal((await issuePermit(req("b".repeat(64)),env,async()=>Response.json({fields}),now)).status,403);
  assert.equal((await issuePermit(req(),env,async()=>Response.json({fields:{...fields,offlineHours:{integerValue:"0"}}}),now)).status,403);
});
test("never trusts decoded token without a successful Firestore read",async()=>{
  let called=false;
  const result=await issuePermit(req(),env,async()=>{called=true;return new Response(null,{status:401})},now);
  assert.equal(called,true);
  assert.equal(result.status,403);
  assert.equal((await result.json()).lease,undefined);
});

test("worker reports safe failure stages without exposing inputs or issuing permits", async()=>{
  const ok=async()=>Response.json({fields});
  for (const [testEnv,fetcher,expected] of [
    [env,async()=>{throw Error("sensitive exception");},"upstream"],
    [env,async()=>Response.json({}),"firestore_response"],
    [{PROJECT_ID:project},ok,"key_missing"],
    [{...env,SIGNING_KEY_JWK:"not a JSON key"},ok,"key_json"],
    [{...env,SIGNING_KEY_JWK:"{}"},ok,"key_import"],
  ]) {
    const response=await issuePermit(req(),testEnv,fetcher,now);
    assert.equal(response.status,503);
    assert.deepEqual(await response.json(),{error:expected});
  }
  const denied=await issuePermit(req(),{PROJECT_ID:project},async()=>new Response(null,{status:403}),now);
  assert.equal(denied.status,403);
  assert.deepEqual(await denied.json(),{error:"denied"});
});
test("worker accepts the nonextractable JWK shape generated by the admin tool",async()=>{
  const exported=JSON.parse(env.SIGNING_KEY_JWK);
  const {kty,crv,x,y,d}=exported;
  const jwk={kty,crv,x,y,d,ext:false,key_ops:["sign"]};
  const response=await issuePermit(req(),{...env,SIGNING_KEY_JWK:"\uFEFF"+JSON.stringify(jwk)+"\r\n"},
    async()=>Response.json({fields}),now);
  assert.equal(response.status,200);
  const [payload,signature]=(await response.json()).lease.split(".");
  assert.equal(await crypto.subtle.verify({name:"ECDSA",hash:"SHA-256"},key.publicKey,
    Buffer.from(signature,"base64url"),Buffer.from(payload,"base64url")),true);
});

test("Cloudflare-compatible fetch uses manual redirects and never follows them",async()=>{
  for (const status of [301,302,303,307,308]) {
    let calls=0;
    const response=await issuePermit(req(),env,async(url,options)=>{
      calls++;
      assert.equal(options.redirect,"manual");
      assert.match(url,/^https:\/\/firestore\.googleapis\.com\//);
      return new Response(null,{status,headers:{Location:"https://other.example.invalid/"}});
    },now);
    assert.equal(calls,1);
    assert.equal(response.status,503);
    assert.deepEqual(await response.json(),{error:"upstream"});
  }
});

test("72h offline with no device cap still binds the signed permit to this computer",async()=>{
  const result=await issuePermit(req("b".repeat(64)),env,async()=>Response.json({fields:{
    ...fields,deviceLimit:{integerValue:"0"},devices:{arrayValue:{values:[]}}}}),now);
  assert.equal(result.status,200);
  const [p,s]=(await result.json()).lease.split(".");
  const raw=Buffer.from(p,"base64url"),payload=JSON.parse(raw);
  assert.equal(await crypto.subtle.verify({name:"ECDSA",hash:"SHA-256"},key.publicKey,Buffer.from(s,"base64url"),raw),true);
  assert.equal(payload.v,2);
  assert.equal(payload.device,"b".repeat(64));
  assert.equal(payload.exp,now+72*3600);
  assert.equal(payload.deviceLimit,0);
  assert.equal(payload.deviceCount,0);
  assert.equal(payload.offlineHours,72);
});
test("perpetual policy is explicit and never exceeds finite account expiry",async()=>{
  for(const cap of [0,2]){
    for(const accountExp of [null,now+365*86400]){
      const result=await issuePermit(req(),env,async()=>Response.json({fields:{
        ...fields,deviceLimit:{integerValue:String(cap)},offlineHours:{integerValue:"-1"},
        expiresAt:accountExp===null?{nullValue:null}:{timestampValue:new Date(accountExp*1000).toISOString()}
      }}),now);
      assert.equal(result.status,200);
      const [p,s]=(await result.json()).lease.split(".");
      const raw=Buffer.from(p,"base64url"),payload=JSON.parse(raw);
      assert.equal(await crypto.subtle.verify({name:"ECDSA",hash:"SHA-256"},key.publicKey,Buffer.from(s,"base64url"),raw),true);
      assert.equal(payload.v,2);
      assert.equal(payload.exp,accountExp);
      assert.equal(payload.accountExp,accountExp);
      assert.equal(payload.offlineHours,-1);
      assert.equal(payload.deviceLimit,cap);
    }
  }
  const denied=await issuePermit(req("b".repeat(64)),env,async()=>Response.json({fields:{
    ...fields,offlineHours:{integerValue:"-1"}}}),now);
  assert.equal(denied.status,403);
});

test("absent legacy cap can be unlimited but malformed explicit cap is never bypassed",async()=>{
  for(const invalid of [{doubleValue:0},{nullValue:null},{integerValue:""},{integerValue:" "},{integerValue:false},null]){
    const r=await issuePermit(req(),env,async()=>Response.json({fields:{...fields,deviceLimit:invalid}}),now);
    assert.equal(r.status,403);
  }
  const {deviceLimit,...legacy}=fields;
  const r=await issuePermit(req(),env,async()=>Response.json({fields:legacy}),now);
  assert.equal(r.status,200);
  assert.equal(JSON.parse(Buffer.from((await r.json()).lease.split(".")[0],"base64url")).deviceLimit,0);
});
